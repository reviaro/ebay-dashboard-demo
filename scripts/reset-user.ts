import './refuse-demo';
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { parseScryptHash } from '../src/lib/auth/password-hash';

const args = process.argv.slice(2);
const value = (name: string) => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
if (args.includes('--help')) {
  console.log('Usage: npm run auth:reset -- --username owner --hash-file /private/path/hash.txt');
} else {
  const username = value('--username'); const file = value('--hash-file');
  if (!username || !file) throw new Error('Provide --username and --hash-file. The file must contain a hash generated by npm run auth:hash.');
  const passwordHash = readFileSync(file, 'utf8').trim();
  parseScryptHash(passwordHash);
  const db = new PrismaClient();
  try {
    await db.$transaction(async tx => {
      const user = await tx.user.findUniqueOrThrow({ where: { username: username.toLowerCase() } });
      await tx.user.update({ where: { id: user.id }, data: { passwordHash, disabledAt: null } });
      await tx.userSession.deleteMany({ where: { userId: user.id } });
      await tx.userInvitation.deleteMany({ where: { userId: user.id } });
    });
    console.log('Password reset; existing sessions and setup links revoked.');
  } finally { await db.$disconnect(); }
}
